// Persistência simplificada, mesmo padrão de src/data/mock/customers.ts.
export function addDeal(deal: Deal) {
  deals.push(deal);
}

export function updateDeal(dealId: string, patch: Partial<Deal>) {
  const deal = deals.find((d) => d.id === dealId);
  if (deal) Object.assign(deal, patch);
  return deal;
}

export function deleteDeal(dealId: string) {
  const idx = deals.findIndex((d) => d.id === dealId);
  if (idx !== -1) deals.splice(idx, 1);
}
