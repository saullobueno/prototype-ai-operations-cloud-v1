// Persistência simplificada: grava de volta neste array compartilhado para que clientes
// criados/editados sobrevivam à navegação dentro da sessão — não sobrevive a um reload.
// Ver docs/06-fluxos-e-ai-moments.md.
export function addCustomer(customer: Customer) {
  customers.push(customer);
}

export function updateCustomer(customerId: string, patch: Partial<Customer>) {
  const customer = customers.find((c) => c.id === customerId);
  if (customer) Object.assign(customer, patch);
  return customer;
}
