// Persistência simplificada: grava de volta neste array compartilhado para que tickets
// criados a partir de uma conversa sobrevivam à navegação dentro da sessão — não sobrevive
// a um reload. Ver docs/06-fluxos-e-ai-moments.md.
export function addTicket(ticket: Ticket) {
  tickets.push(ticket);
}

/** Próximo ID sequencial no padrão "SUP-XXXX" usado por todos os tickets do mock. */
export function nextTicketId(): string {
  const nums = tickets
    .map((t) => parseInt(t.id.replace(/[^\d]/g, ""), 10))
    .filter((n) => !Number.isNaN(n));
  const max = nums.length ? Math.max(...nums) : 1841;
  return `SUP-${max + 1}`;
}
